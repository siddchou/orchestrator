-- Job definition version history for export/import portability
CREATE TABLE JOB_DEFINITION_VERSION (
    VERSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOB_ID NUMBER NOT NULL,
    VERSION_NUMBER NUMBER NOT NULL,
    EXPORT_JSON CLOB NOT NULL,
    VERSION_LABEL VARCHAR2(200),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY VARCHAR2(100),
    CONSTRAINT FK_JOB_VERSION_JOB FOREIGN KEY (JOB_ID) REFERENCES JOB_DEFINITION(JOB_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_JOB_VERSION_JOB ON JOB_DEFINITION_VERSION(JOB_ID);
CREATE UNIQUE INDEX UK_JOB_VERSION_NUM ON JOB_DEFINITION_VERSION(JOB_ID, VERSION_NUMBER);
